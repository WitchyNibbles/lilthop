// The licence texts and the markdown they are written into.

/** @typedef {import("./noticeSources.mjs").Dependency} Dependency */
/** @typedef {Dependency & { chosen: string, texts: { file: string, text: string }[] }} Notice */

/**
 * @typedef {{ text: string, files: string[], users: Notice[] }} TextGroup
 */

/**
 * Each distinct licence text once, with the files it came from and the
 * packages that use it. The most shared texts come first.
 * @param {readonly Notice[]} dependencies
 * @returns {TextGroup[]}
 */
export function groupTexts(dependencies) {
  /** @type {Map<string, TextGroup>} */
  const groups = new Map();
  for (const dependency of dependencies) {
    for (const { file, text } of dependency.texts) {
      const group = groups.get(text) ?? { text, files: [], users: [] };
      if (!group.files.includes(file)) group.files.push(file);
      if (!group.users.includes(dependency)) group.users.push(dependency);
      groups.set(text, group);
    }
  }
  return [...groups.values()].sort(
    (a, b) =>
      b.users.length - a.users.length ||
      (a.text < b.text ? -1 : a.text > b.text ? 1 : 0),
  );
}

