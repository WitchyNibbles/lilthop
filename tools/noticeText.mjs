/**
 * A code fence longer than any run of backticks in the text.
 * @param {string} text
 */
function fenceFor(text) {
  const longest = Math.max(
    0,
    ...(text.match(/`+/g) ?? []).map((run) => run.length),
  );
  return "`".repeat(Math.max(3, longest + 1));
}

/** @param {Dependency} dependency */
function label(dependency) {
  return `${dependency.name} ${dependency.version}`;
}

/**
 * @param {string} title
 * @param {readonly Notice[]} dependencies
 */
function list(title, dependencies) {
  return [
    `### ${title} (${dependencies.length})`,
    "",
    ...dependencies.map((d) => `- ${label(d)}: ${d.chosen}`),
    "",
  ];
}

/**
 * The text of THIRD-PARTY-NOTICES.md.
 * @param {{
 *   dependencies: readonly Notice[],
 * }} input
 */
export function renderNotices({ dependencies }) {
  const of = (/** @type {string} */ ecosystem) =>
    dependencies.filter((d) => d.ecosystem === ecosystem);
  const bare = dependencies.filter((d) => d.texts.length === 0);
  const groups = groupTexts(dependencies);
  const lines = [
    "# Third-party notices",
    "",
    "Lilthop is free software under GPL-3.0-or-later, see `LICENSE`. It ships with the Rust crates and npm packages below, each under its own licence.",
    "",
    "This file is generated by `npm run notices`. Don't edit it by hand.",
    "",
    "SQLite, which comes inside the `rusqlite` crate, is in the public domain.",
    "",
    'The Windows program also links Microsoft\'s WebView2 loader (`WebView2LoaderStatic.lib`), which the `webview2-com-sys` crate carries. Its licence is under "Vendored code" at the end.',
    "",
    'The logo in `docs/brand/` draws the "Lilthop" wordmark from outlines of the Atkinson Hyperlegible Next font (Copyright 2020-2024 The Atkinson Hyperlegible Next Project Authors (https://github.com/googlefonts/atkinson-hyperlegible-next)), under OFL-1.1. Its licence text is under the `@fontsource-variable/atkinson-hyperlegible-next` package below.',
    "",
    "The source code of the packages under MPL-2.0 is on crates.io, at the versions listed here.",
    "",
    "## Packages",
    "",
    ...list("Rust crates", of("crate")),
    ...list("npm packages", of("npm")),
    `## Packages without a licence file (${bare.length})`,
    "",
    bare.length === 0
      ? "None."
      : "These packages carry no licence file, so only the licence name from their metadata is given above.",
    "",
    ...bare.map((d) => `- ${label(d)}: ${d.chosen}`),
    ...(bare.length === 0 ? [] : [""]),
    `## Licence texts (${groups.length})`,
    "",
    "Each distinct text appears once, with the packages that use it.",
    "",
  ];
  groups.forEach((group, index) => {
    const fence = fenceFor(group.text);
    lines.push(
      `### Text ${index + 1}: ${group.files.slice(0, 3).join(", ")}`,
      "",
      `Used by (${group.users.length}): ${group.users.map(label).join(", ")}`,
      "",
      fence,
      group.text,
      fence,
      "",
    );
  });
  const fence = fenceFor(WEBVIEW2_LICENSE);
  lines.push(
    "## Vendored code",
    "",
    "### Microsoft WebView2 loader",
    "",
    "`WebView2LoaderStatic.lib` is linked into the Windows program. It comes from the Microsoft.Web.WebView2 SDK, version 1.0.3800.47, as the `webview2-com-sys` crate carries it. The licence in that SDK:",
    "",
    fence,
    WEBVIEW2_LICENSE,
    fence,
  );
  return `${lines.join("\n").trimEnd()}\n`;
}
